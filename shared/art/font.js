// Ancho en píxeles de un texto en la fuente pequeña (cada letra con 1 píxel de separación).
// "gap" = píxeles entre letras (1 normal; 0 = apretado, para que quepa un texto largo como カラオケ en un cartel estrecho).
export function smallWidth(text, gap = 1) {
  let w = 0;
  for (const ch of text) w += smallGlyph(ch)[0].length + gap;
  return Math.max(0, w - gap);
}
// Pinta un texto en la fuente pequeña. "shadow" (opcional): sombra dura de 1 píxel abajo a la derecha.
export function drawSmall(img, text, x, y, color, shadow = null, gap = 1) {
  let cx = x;
  for (const ch of text) {
    const glyph = smallGlyph(ch);
    for (let j = 0; j < SMALL_H; j++) {
      for (let i = 0; i < glyph[j].length; i++) {
        if (glyph[j][i] !== '#') continue;
        if (shadow !== null) img.set(cx + i + 1, y + j + 1, shadow);
        img.set(cx + i, y + j, color);
      }
    }
    cx += glyph[0].length + gap;
  }
}
// Signo inventado pequeño con aspecto de kanji (3 x 4): textura de rótulo ilegible, como en las referencias.
export function tinyGlyph(img, x, y, color, rng) {
  img.set(x, y, color); img.set(x + 1, y, color); img.set(x + 2, y, color);
  if (rng() < 0.6) img.set(x + 1, y + 1, color);
  if (rng() < 0.5) { img.set(x, y + 2, color); img.set(x + 1, y + 2, color); img.set(x + 2, y + 2, color); }
  else img.set(x + 1, y + 2, color);
  img.set(rng() < 0.5 ? x : x + 2, y + 3, color);
  img.set(x + 1, y + 3, color);
}

// Ancho en píxeles de un texto (5 por letra y 1 de separación), a escala 1, 2...
export const textWidth = (text, scale = 1) => (text.length ? (text.length * (GLYPH_W + 1) - 1) * scale : 0);

// Pinta un texto horizontal. "shadow" (opcional) añade una sombra dura abajo a la derecha; "scale" agranda cada píxel.
export function drawText(img, text, x, y, color, shadow = null, scale = 1) {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    for (let j = 0; j < GLYPH_H; j++) {
      for (let i = 0; i < GLYPH_W; i++) {
        if (glyph[j][i] !== '#') continue;
        if (shadow !== null) img.rect(cx + i * scale + scale, y + j * scale + scale, scale, scale, shadow);
        img.rect(cx + i * scale, y + j * scale, scale, scale, color);
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}

// Signo inventado con aspecto de kanji (5 x 7): trazos horizontales y verticales al azar, simétricos a veces.
export function pseudoGlyph(img, x, y, color, rng) {
  const on = (i, j) => img.set(x + i, y + j, color);
  const rows = [0, 2, 4, 6].filter(() => rng() < 0.55);
  if (rows.length === 0) rows.push(3);
  for (const j of rows) {
    const from = rng() < 0.5 ? 0 : 1;
    const to = rng() < 0.5 ? 4 : 3;
    for (let i = from; i <= to; i++) on(i, j);
  }
  const cols = [0, 2, 4].filter(() => rng() < 0.5);
  if (cols.length === 0) cols.push(2);
  for (const i of cols) {
    const from = Math.floor(rng() * 3);
    const to = 4 + Math.floor(rng() * 3);
    for (let j = from; j <= to; j++) on(i, j);
  }
  if (rng() < 0.5) { on(1, 5); on(0, 6); } // "pata" diagonal
  if (rng() < 0.4) { on(3, 5); on(4, 6); }
}
